fn validate_metadata(name: &str, symbol: &str, uri: &str) -> Result<()> {
    require!(!name.is_empty() && name.len() <= 32, LaunchpadError::InvalidMetadata);
    require!(!symbol.is_empty() && symbol.len() <= 10, LaunchpadError::InvalidMetadata);
    require!(!uri.is_empty() && uri.len() <= 200, LaunchpadError::InvalidMetadata);
    Ok(())
}

fn isqrt_u256(n: U256) -> U256 {
    if n.is_zero() {
        return U256::ZERO;
    }
    let mut x: U256 = U256::ONE << (256 - n.leading_zeros()).div_ceil(2);
    loop {
        let y = (x + n / x) >> 1;
        if y >= x {
            return x;
        }
        x = y;
    }
}

/// DAMM v2 compounding pool from reserves a (token) and b (quote), as Meteora's own launchpad computes it:
/// sqrt_price = ceil(sqrt(b·2^128 / a)), liquidity = min(floor(sqrt(b·2^128 / a)) · a, floor(b·2^128 / sqrt_price)), so
/// the pool pulls ceil(L / sqrt_price) ≤ a and ceil(L · sqrt_price / 2^128) ≤ b. A few units of dust may stay behind.
pub fn compounding_price_and_liquidity(base_amount: u64, quote_amount: u64) -> Result<(u128, u128)> {
    require!(base_amount > 0 && quote_amount > 0, LaunchpadError::ZeroAmount);
    let num: U256 = U256::from(quote_amount) << 128usize;
    let a: U256 = U256::from(base_amount);
    let up = isqrt_u256(num.div_ceil(a));
    let up = if up * up < num.div_ceil(a) { up + U256::ONE } else { up };
    let down = isqrt_u256(num / a);
    let sqrt_price = u128::try_from(up).map_err(|_| LaunchpadError::MathOverflow)?;
    // The pool pulls ceil(L / s) of the token and ceil(L · s / 2^128) of the quote: keep L low enough for both.
    let from_base = down * a;
    let from_quote = num / up;
    let l = if from_base < from_quote { from_base } else { from_quote };
    let liquidity = u128::try_from(l).map_err(|_| LaunchpadError::MathOverflow)?;
    require!((DAMM_MIN_SQRT_PRICE..=DAMM_MAX_SQRT_PRICE).contains(&sqrt_price), LaunchpadError::MathOverflow);
    require!(liquidity > DAMM_DEAD_LIQUIDITY, LaunchpadError::MathOverflow);
    Ok((sqrt_price, liquidity))
}

fn fee_of(amount: u64, fee_bps: u16) -> Result<u64> {
    Ok(((amount as u128 * fee_bps as u128 + BPS as u128 - 1) / BPS as u128) as u64)
}

/// Smallest gross such that gross − fee_of(gross) ≥ net.
fn gross_up(net: u64, fee_bps: u16) -> Result<u64> {
    let mut gross = ((net as u128 * BPS as u128) / (BPS as u128 - fee_bps as u128)) as u64;
    while gross - fee_of(gross, fee_bps)? < net {
        gross += 1;
    }
    Ok(gross)
}

/// Creates the token's metadata, mints the whole supply to the curve's vault and removes the mint authority.
#[allow(clippy::too_many_arguments)]
fn mint_token<'info>(
    payer: &Signer<'info>,
    mint: &InterfaceAccount<'info, Mint>,
    curve: &Account<'info, Curve>,
    base_vault: &InterfaceAccount<'info, TokenAccount>,
    token_program: &Program<'info, Token2022>,
    system: &Program<'info, System>,
    name: String,
    symbol: String,
    uri: String,
) -> Result<()> {
    // Room for the metadata: Token-2022 reallocates the mint, the payer funds the rent.
    let meta = TokenMetadata { name: name.clone(), symbol: symbol.clone(), uri: uri.clone(), ..Default::default() };
    let extra = meta.tlv_size_of().map_err(|_| LaunchpadError::InvalidMetadata)?;
    let new_len = mint.to_account_info().data_len() + extra;
    let lamports = Rent::get()?.minimum_balance(new_len).saturating_sub(mint.to_account_info().lamports());
    if lamports > 0 {
        system_program::transfer(
            CpiContext::new(system.key(), system_program::Transfer { from: payer.to_account_info(), to: mint.to_account_info() }),
            lamports,
        )?;
    }
    let seeds: &[&[&[u8]]] = &[&[CURVE_SEED, curve.mint.as_ref(), &[curve.bump]]];
    token_metadata_initialize(
        CpiContext::new_with_signer(
            token_program.key(),
            TokenMetadataInitialize {
                program_id: token_program.to_account_info(),
                metadata: mint.to_account_info(),
                update_authority: curve.to_account_info(),
                mint_authority: curve.to_account_info(),
                mint: mint.to_account_info(),
            },
            seeds,
        ),
        name,
        symbol,
        uri,
    )?;
    token_2022::mint_to(
        CpiContext::new_with_signer(
            token_program.key(),
            MintTo { mint: mint.to_account_info(), to: base_vault.to_account_info(), authority: curve.to_account_info() },
            seeds,
        ),
        TOTAL_SUPPLY,
    )?;
    token_2022::set_authority(
        CpiContext::new_with_signer(
            token_program.key(),
            SetAuthority { current_authority: curve.to_account_info(), account_or_mint: mint.to_account_info() },
            seeds,
        ),
        AuthorityType::MintTokens,
        None,
    )?;
    Ok(())
}

