pub enum LaunchpadError {
    #[msg("Not allowed")]
    Unauthorized,
    #[msg("Invalid configuration")]
    InvalidConfig,
    #[msg("Invalid name, symbol or uri")]
    InvalidMetadata,
    #[msg("Wrong quote token")]
    InvalidQuote,
    #[msg("Only the artist's creator can do this")]
    NotArtistCreator,
    #[msg("Amount must be positive")]
    ZeroAmount,
    #[msg("Price moved beyond the slippage limit")]
    Slippage,
    #[msg("The curve is complete: trade on the pool")]
    CurveComplete,
    #[msg("Not enough liquidity on the curve")]
    InsufficientLiquidity,
    #[msg("Treasury spending is frozen")]
    TreasuryFrozen,
    #[msg("Daily treasury spending cap reached")]
    DailyCapExceeded,
    #[msg("Math overflow")]
    MathOverflow,
    #[msg("The curve is not complete yet")]
    CurveNotComplete,
    #[msg("Already migrated")]
    AlreadyMigrated,
    #[msg("Not this token's pool")]
    WrongPool,
    #[msg("Trading opens once the token's pool is armed")]
    PoolNotArmed,
    #[msg("The pool is already armed")]
    AlreadyArmed,
}
