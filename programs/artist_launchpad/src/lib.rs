    /// Launches an artist: its token ($JO), on a curve priced in SOL. Co-signed by the operator.
    pub fn create_artist(ctx: Context<CreateArtist>, name: String, symbol: String, uri: String) -> Result<()> {
        validate_metadata(&name, &symbol, &uri)?;
        let config = &ctx.accounts.config;
        let mint_key = ctx.accounts.mint.key();

        let artist = &mut ctx.accounts.artist;
        artist.creator = ctx.accounts.creator.key();
        artist.mint = mint_key;
        artist.song_count = 0;
        artist.spend_day = 0;
        artist.spent_today = 0;
        artist.bump = ctx.bumps.artist;
        artist.treasury_bump = ctx.bumps.treasury;

        let curve = &mut ctx.accounts.curve;
        curve.init(mint_key, WSOL, mint_key, KIND_ARTIST, config.artist_curve, config, ctx.bumps.curve);

        mint_token(
            &ctx.accounts.creator,
            &ctx.accounts.mint,
            &ctx.accounts.curve,
            &ctx.accounts.base_vault,
            &ctx.accounts.token_program,
            &ctx.accounts.system_program,
            name.clone(),
            symbol.clone(),
            uri.clone(),
        )?;

        emit!(ArtistCreated { artist: ctx.accounts.artist.key(), mint: mint_key, creator: ctx.accounts.creator.key(), name, symbol, uri });
        Ok(())
    }

