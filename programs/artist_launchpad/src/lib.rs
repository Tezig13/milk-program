#[account]
#[derive(InitSpace)]
pub struct Curve {
    pub mint: Pubkey,
    pub quote_mint: Pubkey,
    /// The artist this token belongs to (its own mint for an artist token).
    pub artist_mint: Pubkey,
    pub kind: u8,
    pub virtual_base: u128,
    pub virtual_quote: u128,
    /// Tokens still for sale on the curve.
    pub real_base: u64,
    /// Quote reserves raised by the curve (fees excluded).
    pub real_quote: u64,
    pub fees_platform: u64,
    pub fees_creator: u64,
    pub fees_treasury: u64,
    /// Snapshot of the fee terms at launch.
    pub fee_bps: u16,
    pub platform_share_bps: u16,
    pub creator_share_bps: u16,
    pub complete: bool,
    pub migrated: bool,
    pub bump: u8,
}

impl Curve {
    #[allow(clippy::too_many_arguments)]
    fn init(&mut self, mint: Pubkey, quote_mint: Pubkey, artist_mint: Pubkey, kind: u8, p: CurveParams, c: &Config, bump: u8) {
        self.mint = mint;
        self.quote_mint = quote_mint;
        self.artist_mint = artist_mint;
        self.kind = kind;
        self.virtual_base = p.virtual_base as u128;
        self.virtual_quote = p.virtual_quote as u128;
        self.real_base = p.curve_supply;
        self.real_quote = 0;
        self.fees_platform = 0;
        self.fees_creator = 0;
        self.fees_treasury = 0;
        self.fee_bps = c.fee_bps;
        self.platform_share_bps = c.platform_share_bps;
        self.creator_share_bps = c.creator_share_bps;
        self.complete = false;
        self.migrated = false;
        self.bump = bump;
    }

    /// Tokens out for `quote_in` (after fee).
    pub fn base_out(&self, quote_in: u64) -> Result<u64> {
        let out = self.virtual_base * quote_in as u128 / (self.virtual_quote + quote_in as u128);
        Ok(u64::try_from(out).map_err(|_| LaunchpadError::MathOverflow)?)
    }

    /// Quote (before fee) needed to buy exactly `base_out`, rounded up.
    pub fn quote_in_for(&self, base_out: u64) -> Result<u64> {
        let b = base_out as u128;
        require!(b < self.virtual_base, LaunchpadError::MathOverflow);
        let q = (self.virtual_quote * b + (self.virtual_base - b) - 1) / (self.virtual_base - b);
        Ok(u64::try_from(q).map_err(|_| LaunchpadError::MathOverflow)?)
    }

    /// Quote out (before fee) for selling `base_in`.
    pub fn quote_out(&self, base_in: u64) -> Result<u64> {
        let out = self.virtual_quote * base_in as u128 / (self.virtual_base + base_in as u128);
        Ok(u64::try_from(out).map_err(|_| LaunchpadError::MathOverflow)?)
    }

    fn accrue(&mut self, fee: u64) -> Result<()> {
        let platform = (fee as u128 * self.platform_share_bps as u128 / BPS as u128) as u64;
        let creator = (fee as u128 * self.creator_share_bps as u128 / BPS as u128) as u64;
        let treasury = fee - platform - creator;
        self.fees_platform = self.fees_platform.checked_add(platform).ok_or(LaunchpadError::MathOverflow)?;
        self.fees_creator = self.fees_creator.checked_add(creator).ok_or(LaunchpadError::MathOverflow)?;
        self.fees_treasury = self.fees_treasury.checked_add(treasury).ok_or(LaunchpadError::MathOverflow)?;
        Ok(())
    }
}

