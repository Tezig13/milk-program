//! AI artist launchpad.
//!
//! An AI artist (look, art direction, music, generated off-chain by the platform) is launched with its own token,
//! e.g. $JO, on a bonding curve priced in SOL (wrapped SOL). Every song the artist releases is launched as its own
//! token on a bonding curve priced in the artist's token: $A/$JO, $B/$JO.
//!
//! - Tokens: Token-2022, 6 decimals, 1B supply, metadata (name, symbol, uri) in the mint. The whole supply is minted
//!   once to the curve, then the mint authority is removed: nobody can ever mint more.
//! - Curve: constant product on virtual reserves (pump-style). When its tokens are sold out the curve completes and
//!   the liquidity migrates to a Meteora DAMM v2 pool (phase 2), where the program keeps a locked position.
//! - Fees: `fee_bps` (1%) of every trade, taken in the quote token (SOL for artists, the artist token for songs),
//!   split platform / creator / artist treasury (30 / 40 / 30). Anyone can push the split out (`claim_fees`).
//! - Treasury: each artist has a treasury (PDA) that pays its generations (music, visuals). The backend operator
//!   spends it, within a daily cap, to the platform's ops wallet; the admin can freeze all treasury spending.
//! - Launches are co-signed by the operator: only artists and songs actually generated by the platform go live.
//!   Only an artist's creator can release its songs.

