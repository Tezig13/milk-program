#[derive(AnchorSerialize, AnchorDeserialize, Clone, Copy, InitSpace, Debug, PartialEq)]
pub struct CurveParams {
    /// Virtual reserves the price starts from (base: token units; quote: quote units).
    pub virtual_base: u64,
    pub virtual_quote: u64,
    /// Tokens sold on the curve; the rest of the supply seeds the pool at graduation.
    pub curve_supply: u64,
}

#[derive(AnchorSerialize, AnchorDeserialize, Clone, Copy, Debug)]
pub struct ConfigParams {
    pub operator: Pubkey,
    pub platform_wallet: Pubkey,
    pub ops_wallet: Pubkey,
    pub fee_bps: u16,
    pub platform_share_bps: u16,
    pub creator_share_bps: u16,
    pub treasury_daily_cap_bps: u16,
    pub artist_curve: CurveParams,
    pub song_curve: CurveParams,
}

impl ConfigParams {
    fn validate(&self) -> Result<()> {
        require!(self.fee_bps <= MAX_FEE_BPS, LaunchpadError::InvalidConfig);
        require!(self.platform_share_bps as u64 + self.creator_share_bps as u64 <= BPS, LaunchpadError::InvalidConfig);
        require!(self.treasury_daily_cap_bps as u64 <= BPS, LaunchpadError::InvalidConfig);
        for c in [self.artist_curve, self.song_curve] {
            require!(c.curve_supply > 0 && c.curve_supply < TOTAL_SUPPLY, LaunchpadError::InvalidConfig);
            require!(c.virtual_base > c.curve_supply && c.virtual_quote > 0, LaunchpadError::InvalidConfig);
        }
        Ok(())
    }
}

